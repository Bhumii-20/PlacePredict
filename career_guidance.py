# =========================================================
# CAREER RECOMMENDATION FUNCTION
# =========================================================

def get_career_recommendation(
    preferred_career,
    technical_skills="",
    programming_languages="",
    interests="",
    stream=""
):
    """
    Generate career recommendations based on
    student's preferred field, skills, interests
    and stream.
    """

    # Default career
    if preferred_career in CAREER_DATA:

        career = preferred_career

    else:

        career = "Software Development"


    career_info = CAREER_DATA[career]

    student_text = (
        technical_skills + " "
        + programming_languages + " "
        + interests + " "
        + stream
    ).lower()


    # -----------------------------------------------------
    # Find matching skills
    # -----------------------------------------------------

    matched_skills = []
    missing_skills = []

    for skill in career_info["skills"]:

        if skill.lower() in student_text:

            matched_skills.append(skill)

        else:

            missing_skills.append(skill)


    # -----------------------------------------------------
    # Career match score
    # -----------------------------------------------------

    total_skills = len(
        career_info["skills"]
    )

    if total_skills > 0:

        skill_match_percentage = (
            len(matched_skills)
            / total_skills
        ) * 100

    else:

        skill_match_percentage = 0


    return {
        "career": career,
        "roles": career_info["roles"],
        "required_skills": career_info["skills"],
        "matched_skills": matched_skills,
        "missing_skills": missing_skills,
        "certifications": career_info["certifications"],
        "match_percentage": round(
            skill_match_percentage,
            1
        )
    }